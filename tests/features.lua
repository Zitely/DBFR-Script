return function(test, equal, mock)
    local Main = require("src.Main")
    local Markers = require("src.WorldMarkers")
    local function start()
        mock.reset()
        local root = mock.object("Part", "HumanoidRootPart", mock.character,
            {Position = Vector3.new(0, 0, 0), CFrame = CFrame.new(0, 0, 0), CanCollide = true})
        local app = Main.start()
        return app, app.features, root
    end
    local function remote(name, class, callback)
        local folder = mock.replicatedStorage:FindFirstChild("Remotes")
            or mock.object("Folder", "Remotes", mock.replicatedStorage)
        local object = mock.object(class or "RemoteEvent", name, folder)
        local calls = {}
        object[class == "RemoteFunction" and "InvokeServer" or "FireServer"] = function(_, ...)
            calls[#calls + 1] = {...}
            if callback then callback(...) end
        end
        return object, calls
    end
    test("movement restores properties on off, replacement character, and unload", function()
        local app, hub = start()
        hub:set("speed", true); mock.tick(0.1)
        equal(mock.humanoid.WalkSpeed, 50)
        local old = mock.humanoid
        local char = mock.object("Model", "NewCharacter", workspace)
        local hum = mock.object("Humanoid", "Humanoid", char, {Health = 100, WalkSpeed = 24})
        mock.player.Character = char
        mock.tick(0.2); equal(old.WalkSpeed, 16); equal(hum.WalkSpeed, 50)
        hub:set("speed", false); equal(hum.WalkSpeed, 24)
        hub:set("speed", true); mock.tick(0.2); app.unload(); equal(hum.WalkSpeed, 24)
    end)
