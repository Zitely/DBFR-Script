    test("optional remote tools use supplied argument shapes and bounded cadences", function()
        local app, hub = start()
        local _, punches = remote("KeyAttack")
        local _, blasts = remote("BlastMoves")
        local _, transforms = remote("Transformtion")
        local _, saves = remote("SaveData")
        for _, id in ipairs({"punch", "blast", "transform", "save"}) do hub:set(id, true) end
        mock.tick(0.1)
        equal(punches[1][1], "EffectSTA"); equal(#blasts[1], 0); equal(transforms[1][1], true)
        equal(#saves, 0)
        mock.tick(0.05); equal(#punches, 1); equal(#blasts, 1)
        mock.tick(30); equal(#punches, 2); equal(#saves, 1) -- No burst after a long frame.
        app.toggle(); mock.tick(1); equal(#punches, 2)
        app.unload(); mock.tick(60); equal(#saves, 1)
    end)
    test("block permits one yielding request and releases after an in-flight stop", function()
        local app, hub = start()
        local entered = false
        local _, calls = remote("MainFunction", "RemoteFunction", function(args)
            if args[2] then
                assert(not entered); entered = true
                hub:step(10); hub:step(20)
                hub:set("block", false)
            end
        end)
        hub:set("block", true); mock.tick()
