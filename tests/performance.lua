return function(test, equal, mock)
    local Bindings = require("src.Bindings")
    local Main = require("src.Main")
    local function inventory(count)
        for i = 1, count do mock.object("TextLabel", "Inventory" .. i, mock.hud, {Text = "Inventory item " .. i}) end
    end
    local function warm(scanner, frames)
        for i = 1, frames do scanner:snapshot(i / 60) end
        assert(scanner.index.head > scanner.index.tail, "Discovery did not drain within the work budget")
    end
    test("paused application does zero GUI discovery across 120 frames with 3000 labels", function()
        mock.reset(); inventory(3000)
        local app = Main.start()
        mock.resetMetrics()
        for i = 1, 120 do mock.tick(1 / 60) end
        equal(mock.metrics.fullScans, 0); equal(mock.metrics.childrenReads, 0); equal(mock.metrics.typeChecks, 0)
        app.unload()
    end)
    test("bootstrap discovery is split across frames and does not enumerate whole trees", function()
        mock.reset(); inventory(3000)
        local b = Bindings.new(mock.player)
        mock.resetMetrics(); b:snapshot(0)
        assert(b.index.lastWork <= 96)
        assert(b.index.head <= b.index.tail, "Large discovery should not finish in one frame")
        equal(mock.metrics.fullScans, 0)
        warm(b, 240)
        equal(mock.metrics.fullScans, 0); b:pause()
    end)
    test("steady-state sampling ignores thousands of unrelated labels", function()
        mock.reset(); inventory(3000)
        local note = mock.object("TextLabel", "Note", mock.hud, {Text = "Q",
            AbsolutePosition = Vector2.new(700, 598), AbsoluteSize = Vector2.new(40, 28)})
        local b = Bindings.new(mock.player)
        warm(b, 240)
        mock.resetMetrics(); b.candidateReads = 0
        local sample
        for i = 1, 120 do
            note.AbsolutePosition = Vector2.new(700 + i, 598)
            sample = b:snapshot(4 + i / 60)
        end
        equal(#sample.notes, 1); equal(sample.notes[1].x, 840)
        equal(mock.metrics.fullScans, 0); equal(mock.metrics.childrenReads, 0)
        assert(b.candidateReads <= 130, "Unrelated GUI entered the hot path")
        assert(mock.metrics.typeChecks < 10000)
        print(string.format("PERF active 3000-label fixture, 120 frames: %d full scans, %d type checks, %d candidate reads",
            mock.metrics.fullScans, mock.metrics.typeChecks, b.candidateReads))
        b:pause()
    end)
    test("new notes and changing text are indexed through events", function()
        mock.reset()
        local b = Bindings.new(mock.player); b:snapshot(0)
        local note = mock.object("TextLabel", "Pooled", mock.hud, {Text = "Q",
            AbsolutePosition = Vector2.new(700, 598), AbsoluteSize = Vector2.new(40, 28)})
        equal(b:snapshot(0.1).notes[1].kind, "q")
        note.Text = "E"
        equal(b:snapshot(0.2).notes[1].kind, "e")
        note:Destroy(); equal(#b:snapshot(0.3).notes, 0)
        equal(b.records[note], nil); b:pause()
    end)
    test("live prompts are discovered before a large bootstrap queue finishes", function()
        mock.reset(); inventory(3000)
        local b = Bindings.new(mock.player); b:snapshot(0)
        assert(b.index.head <= b.index.tail)
        local note = mock.object("TextLabel", "LivePrompt", mock.hud, {Text = "Q",
            AbsolutePosition = Vector2.new(800, 598), AbsoluteSize = Vector2.new(40, 28)})
        local sample = b:snapshot(0.02)
        equal(#sample.notes, 1); equal(sample.notes[1].id, note)
        assert(b.index.lastWork <= 96); b:pause()
    end)
    test("repeated CoreGui reconnect dialogs are discovered without tree rescans", function()
        mock.reset()
        local b = Bindings.new(mock.player); b:snapshot(0)
        mock.resetMetrics()
        for i = 1, 2 do
            local popup = mock.object("ScreenGui", "Disconnect" .. i, mock.coreGui)
            local button = mock.object("TextButton", "Button", popup, {Text = "Reconnect"})
            equal(b:snapshot(i * 2).controls.reconnect, button)
            popup:Destroy(); equal(b:snapshot(i * 2 + 0.1).reconnect, false)
        end
        equal(mock.metrics.fullScans, 0); b:pause()
    end)
    test("turning off releases observers and stays idle after more UI is added", function()
        mock.reset()
        local app = Main.start()
        app.toggle(); mock.tick(); app.toggle()
        equal(next(app.scanner.index.records), nil)
        for _, c in ipairs(mock.playerGui.DescendantAdded.listeners) do equal(c.Connected, false) end
        mock.resetMetrics(); inventory(100)
        for i = 1, 120 do mock.tick(1 / 60) end
        equal(mock.metrics.fullScans, 0); equal(mock.metrics.childrenReads, 0); equal(mock.metrics.typeChecks, 0)
        app.unload()
    end)
    test("replacing PlayerGui refreshes cached controls and discards old observers", function()
        mock.reset()
        local oldStart = mock.object("TextButton", "Start", mock.hud, {Text = "Start"})
        local b = Bindings.new(mock.player); equal(b:snapshot(0).controls.start, oldStart)
        mock.playerGui:Destroy()
        mock.playerGui = mock.object("PlayerGui", "PlayerGui", mock.player)
        local hud = mock.object("ScreenGui", "NewHUD", mock.playerGui)
        local newStart = mock.object("TextButton", "Start", hud, {Text = "Start"})
        equal(b:snapshot(2.1).controls.start, newStart)
        equal(b.records[oldStart], nil); b:pause()
    end)
    test("an automatically named image teaches later anonymous copies of its sprite", function()
        mock.reset()
        local anonymous = mock.object("ImageLabel", "Icon", mock.hud, {Image = "rbxassetid://777",
            AbsolutePosition = Vector2.new(700, 526), AbsoluteSize = Vector2.new(40, 28)})
        local b = Bindings.new(mock.player); equal(#b:snapshot(0).notes, 0)
        mock.object("ImageLabel", "MouseButton1", mock.hud, {Image = "rbxassetid://777"})
        local sample = b:snapshot(0.1)
        equal(sample.notes[1].id, anonymous); equal(sample.notes[1].kind, "left")
        b:pause()
    end)
    test("hub keeps one Chamber toggle and shortcut alongside optional feature tabs", function()
        mock.reset()
        local app = Main.start()
        equal(#app.ui.order, 1); equal(#mock.uis.InputBegan.listeners, 1)
        equal(#app.ui.pageOrder, 6); equal(app.ui.selectedPage, "Chamber")
        equal(app.ui.controls.autoHtc, nil); equal(app.ui.controls.overnight, nil)
        equal(app.ui.bindingLabels, nil)
        app.unload()
    end)
end
