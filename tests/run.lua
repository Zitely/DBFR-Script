package.path = "./?.lua;" .. package.path
local Config = require("src.Config")
local Engine = require("src.Engine")
local Rhythm = require("src.Rhythm")
local Timer = require("src.Timer")
local passed, failed = 0, 0
local function equal(actual, expected, message)
    assert(actual == expected, (message or "values differ") .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function test(name, fn)
    local ok, reason = pcall(fn)
    if ok then passed = passed + 1; print("PASS " .. name)
    else failed = failed + 1; print("FAIL " .. name .. ": " .. tostring(reason)) end
end
local function engine(overrides)
    local e = Engine.new(Config.new(overrides))
    e:setActive(true, 0)
    return e
end
local function enterTraining(e, at)
    at = at or 0
    local action = e:step({start = true}, at)
    equal(action.kind, "start")
    e:complete(action, true, at + 1)
    for i = 1, 3 do e:step({training = true}, at + 1 + i * 0.1) end
    equal(e.state, "training")
end
local function fakeInput()
    return {events = {}, down = function(self, kind) self.events[#self.events + 1] = "+" .. kind end,
        up = function(self, kind) self.events[#self.events + 1] = "-" .. kind end}
end

test("configuration validates types, bounds, and non-finite numbers", function()
    local c = Config.new({spamHoldMs = -10, teleportAttempts = 99, afkDurationMinutes = 99, autoStart = "yes", timingOffsetMs = 0 / 0, lostSeconds = math.huge, unknown = true})
    equal(c.spamHoldMs, 10); equal(c.autoStart, true); equal(c.timingOffsetMs, -40)
    equal(c.lostSeconds, 8); equal(c.teleportAttempts, 5); equal(c.afkDurationMinutes, nil); equal(c.unknown, nil)
end)
test("timer accepts HUD text and rejects invalid ranges", function()
    equal(Timer.parse("Time Left: 1:36:22"), 5782)
    equal(Timer.parse("1:60:22"), nil); equal(Timer.parse("2:00:61"), nil)
    equal(Timer.parse("unknown"), nil); equal(Timer.format(nil), "--:--:--")
end)
test("timer needs consecutive reads, extrapolates, and survives missing text", function()
    local t = Timer.new()
    equal(t:observe(5000, 0), false); equal(t:observe(4998, 2), true)
    equal(t:observe(nil, 5), false); equal(t:remaining(212), 4788)
    equal(t:observe(7000, 213), false); equal(t:remaining(213), 4787)
    t:reset(); equal(t:remaining(214), nil)
end)
test("Start overrides false training and requires three fresh samples", function()
    local e = engine()
    local a = e:step({start = true, training = true}, 0)
    equal(a.kind, "start"); equal(e:canPlay({training = true}), false)
    e:complete(a, true, 1)
    e:step({start = true, training = true}, 2); equal(e.fresh, 0)
    e:step({training = true}, 3); e:step({training = true}, 3.1)
    equal(e.state, "starting")
    e:step({training = true}, 3.2); equal(e.state, "training")
    equal(e:canPlay({training = true}), true)
end)
test("enabling during a recognized minigame adopts it without another Start", function()
    local e = engine()
    local s = {training = true, alive = true, notes = {{kind = "q"}}}
    e:step(s, 0.1); e:step(s, 0.2)
    equal(e.state, "seeking"); equal(e:canPlay(s), false)
    e:step(s, 0.3)
    equal(e.state, "training"); equal(e.requiresStart, false)
    equal(e:canPlay(s), true)
end)
test("adoption needs live prompts and does not bypass a visible Start or respawn", function()
    local e = engine()
    for i = 1, 3 do e:step({training = true, alive = true, notes = {}}, i * 0.1) end
    equal(e.state, "seeking"); equal(e.requiresStart, true)
    for i = 4, 6 do e:step({training = true, alive = false, notes = {{kind = "q"}}}, i * 0.1) end
    equal(e.state, "seeking")
    local action = e:step({start = true, training = true, alive = true, notes = {{kind = "q"}}}, 0.7)
    equal(action.kind, "start")
    e:complete(action, true, 1)
    e.state, e.since, e.readyAfter, e.requiresStart = "respawning", 1, 9, true
    for i = 2, 12 do e:step({training = true, alive = true, notes = {{kind = "q"}}}, i) end
    equal(e.state, "respawning"); equal(e:canPlay({}), false)
end)
test("respawn uses menu, entry, confirmation, character wait, then a fresh Start", function()
    local e = engine()
    enterTraining(e)
    local s = {menu = true, bindingsReady = true}
    e:step(s, 4)
    local a = e:step(s, 10); equal(a.kind, "menu"); e:complete(a, true, 11)
    a = e:step({respawn = true, start = true}, 11.1); equal(a.kind, "respawn"); e:complete(a, true, 12)
    a = e:step({confirm = true, start = true}, 12.1); equal(a.kind, "confirm"); e:complete(a, true, 13)
    for i = 14, 20 do equal(e:step({start = true, training = true, alive = true}, i), nil) end
    equal(e.state, "respawning"); equal(e.requiresStart, true)
    for i = 1, 3 do e:step({start = true, alive = true}, 21 + i * 0.1) end
    equal(e.state, "seeking")
    a = e:step({start = true, training = true}, 21.4); equal(a.kind, "start")
    e:complete(a, true, 22)
    for i = 1, 3 do e:step({training = true}, 22 + i * 0.1) end
    equal(e.state, "training"); equal(e.sessions, 2)
end)
test("persistent Start is insufficient while the character is dead", function()
    local e = engine()
    e.state, e.since, e.readyAfter = "respawning", 0, 8
    for i = 8, 12 do e:step({start = true, alive = false}, i) end
    equal(e.state, "respawning")
    e:step({start = true, alive = false}, 46); equal(e.active, false)
end)
test("unmapped prompts stop recovery instead of repeatedly respawning", function()
    local e = engine()
