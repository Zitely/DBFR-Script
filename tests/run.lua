package.path = "./?.lua;" .. package.path
local Config = require("src.Config")
local Engine = require("src.Engine")
local Rhythm = require("src.Rhythm")
local Timer = require("src.Timer")
local passed, failed = 0, 0
local function equal(actual, expected, message)
    assert(actual == expected, (message or "values differ") .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
end
local function test(name, fn)
    local ok, reason = pcall(fn)
    if ok then passed = passed + 1; print("PASS " .. name)
    else failed = failed + 1; print("FAIL " .. name .. ": " .. tostring(reason)) end
end
local function engine(overrides)
    local e = Engine.new(Config.new(overrides))
    e:setActive(true, 0)
    return e
end
local function enterTraining(e, at)
    at = at or 0
    local action = e:step({start = true}, at)
    equal(action.kind, "start")
    e:complete(action, true, at + 1)
    for i = 1, 3 do e:step({training = true}, at + 1 + i * 0.1) end
    equal(e.state, "training")
end
local function fakeInput()
    return {events = {}, down = function(self, kind) self.events[#self.events + 1] = "+" .. kind end,
        up = function(self, kind) self.events[#self.events + 1] = "-" .. kind end}
end

test("configuration validates types, bounds, and non-finite numbers", function()
    local c = Config.new({spamHoldMs = -10, afkDurationMinutes = 99, autoStart = "yes", timingOffsetMs = 0 / 0, lostSeconds = math.huge, unknown = true})
    equal(c.spamHoldMs, 10); equal(c.autoStart, true); equal(c.timingOffsetMs, -40)
    equal(c.lostSeconds, 8); equal(c.afkDurationMinutes, 60); equal(c.unknown, nil)
end)
test("timer accepts HUD text and rejects invalid ranges", function()
    equal(Timer.parse("Time Left: 1:36:22"), 5782)
    equal(Timer.parse("1:60:22"), nil); equal(Timer.parse("2:00:61"), nil)
    equal(Timer.parse("unknown"), nil); equal(Timer.format(nil), "--:--:--")
end)
test("timer needs consecutive reads, extrapolates, and survives missing text", function()
    local t = Timer.new()
    equal(t:observe(5000, 0), false); equal(t:observe(4998, 2), true)
    equal(t:observe(nil, 5), false); equal(t:remaining(212), 4788)
    equal(t:observe(7000, 213), false); equal(t:remaining(213), 4787)
    t:reset(); equal(t:remaining(214), nil)
end)
test("Start overrides false training and requires three fresh samples", function()
    local e = engine()
    local a = e:step({start = true, training = true}, 0)
    equal(a.kind, "start"); equal(e:canPlay({training = true}), false)
    e:complete(a, true, 1)
    e:step({start = true, training = true}, 2); equal(e.fresh, 0)
    e:step({training = true}, 3); e:step({training = true}, 3.1)
    equal(e.state, "starting")
    e:step({training = true}, 3.2); equal(e.state, "training")
    equal(e:canPlay({training = true}), true)
end)
test("enabling during a recognized minigame adopts it without another Start", function()
    local e = engine()
    local s = {training = true, alive = true, notes = {{kind = "q"}}}
    e:step(s, 0.1); e:step(s, 0.2)
    equal(e.state, "seeking"); equal(e:canPlay(s), false)
    e:step(s, 0.3)
    equal(e.state, "training"); equal(e.requiresStart, false)
    equal(e:canPlay(s), true)
end)
test("adoption needs live prompts and does not bypass a visible Start or respawn", function()
    local e = engine()
    for i = 1, 3 do e:step({training = true, alive = true, notes = {}}, i * 0.1) end
    equal(e.state, "seeking"); equal(e.requiresStart, true)
    for i = 4, 6 do e:step({training = true, alive = false, notes = {{kind = "q"}}}, i * 0.1) end
    equal(e.state, "seeking")
    local action = e:step({start = true, training = true, alive = true, notes = {{kind = "q"}}}, 0.7)
    equal(action.kind, "start")
    e:complete(action, true, 1)
    e.state, e.since, e.readyAfter, e.requiresStart = "respawning", 1, 9, true
    for i = 2, 12 do e:step({training = true, alive = true, notes = {{kind = "q"}}}, i) end
    equal(e.state, "respawning"); equal(e:canPlay({}), false)
end)
test("respawn uses menu, entry, confirmation, character wait, then a fresh Start", function()
    local e = engine()
    enterTraining(e)
    local s = {menu = true, bindingsReady = true}
    e:step(s, 4)
    local a = e:step(s, 10); equal(a.kind, "menu"); e:complete(a, true, 11)
    a = e:step({respawn = true, start = true}, 11.1); equal(a.kind, "respawn"); e:complete(a, true, 12)
    a = e:step({confirm = true, start = true}, 12.1); equal(a.kind, "confirm"); e:complete(a, true, 13)
    for i = 14, 20 do equal(e:step({start = true, training = true, alive = true}, i), nil) end
    equal(e.state, "respawning"); equal(e.requiresStart, true)
    for i = 1, 3 do e:step({start = true, alive = true}, 21 + i * 0.1) end
    equal(e.state, "seeking")
    a = e:step({start = true, training = true}, 21.4); equal(a.kind, "start")
    e:complete(a, true, 22)
    for i = 1, 3 do e:step({training = true}, 22 + i * 0.1) end
    equal(e.state, "training"); equal(e.sessions, 2)
end)
test("persistent Start is insufficient while the character is dead", function()
    local e = engine()
    e.state, e.since, e.readyAfter = "respawning", 0, 8
    for i = 8, 12 do e:step({start = true, alive = false}, i) end
    equal(e.state, "respawning")
    e:step({start = true, alive = false}, 46); equal(e.active, false)
end)
test("unmapped prompts stop recovery instead of repeatedly respawning", function()
    local e = engine()
    e:step({menu = true, bindingsReady = false}, 16)
    equal(e.active, false); assert(e.status:find("not recognized automatically"))
end)
test("low health enters direct reset recovery without Roblox menu input", function()
    local e = engine({recoveryAttempts = 5})
    local s = {trainingKnown = true, needsRecovery = true}
    local a = e:step(s, 0)
    equal(a, nil); equal(e.recoveryCount, 1)
    equal(e.state, "respawning"); equal(e.requiresStart, true)
end)
test("failed UI action halts with its error", function()
    local e = engine()
    local a = e:step({start = true}, 0)
    e:complete(a, false, 1, "unsupported executor")
    equal(e.active, false); assert(e.status:find("unsupported executor"))
end)
test("pause invalidates a pending action and blocks reconnect checks", function()
    local e = engine()
    local a = e:step({start = true}, 0)
    e:setActive(false, 0.1); e:complete(a, true, 1)
    for i = 1, 5 do equal(e:step({reconnect = true}, i * 2), nil) end
    equal(e.state, "paused"); equal(e.startCount, 0)
end)
test("a single reconnect candidate pauses input but never clicks", function()
    local e = engine()
    enterTraining(e)
    equal(e:step({reconnect = true, training = true}, 4), nil)
    equal(e:canPlay({training = true}), false)
    e:step({training = true}, 6)
    equal(e.state, "training"); equal(e:canPlay({training = true}), true)
end)
test("brief gaps between prompts keep the current rhythm session", function()
    local e = engine()
    enterTraining(e)
    e:step({training = false}, 2)
    equal(e:canPlay({training = false}), true)
    e:step({training = false}, 4)
    equal(e:canPlay({training = false}), false)
end)
test("reconnect detects at launch without an AFK cycle", function()
    local e = engine()
    equal(e:step({reconnect = true}, 0), nil)
    local a = e:step({reconnect = true}, 2)
    equal(a.kind, "reconnect")
end)
test("reconnect cancels an older pending recovery action", function()
    local e = engine()
    e.state, e.since = "lost", 0; e.lastTraining = 0
    local old = e:step({menu = true, bindingsReady = true}, 10)
    equal(old.kind, "menu")
    e:step({reconnect = true}, 12)
    local a = e:step({reconnect = true}, 14)
    equal(a.kind, "reconnect")
    e:complete(old, true, 14.1); equal(e.pending, a)
end)
test("reconnect retry cooldown begins after the click and stays bounded", function()
    local e = engine()
    e:step({reconnect = true}, 0)
    for attempt = 1, 3 do
        local at = (attempt - 1) * 12 + 2
        local a = e:step({reconnect = true}, at)
        equal(a.kind, "reconnect")
        e:complete(a, true, at + 2)
        equal(e:step({reconnect = true}, at + 10), nil)
    end
    e:step({reconnect = true}, 38)
    equal(e.active, false)
end)
test("two reconnect cycles each receive a new retry budget and keep the new timer", function()
    local e = engine()
    enterTraining(e)
    for cycle = 1, 2 do
        local at = (cycle - 1) * 250 + 10
        e:step({reconnect = true}, at)
        local a = e:step({reconnect = true}, at + 2)
        equal(a.kind, "reconnect"); e:complete(a, true, at + 3)
        equal(e.reconnectCount, 1)
        e:step({start = true, timer = 7000}, at + 4)
        e:step({start = true, timer = 6998}, at + 6)
        a = e:step({start = true, timer = 6993}, at + 11)
        equal(a.kind, "start"); e:complete(a, true, at + 12)
        for i = 1, 3 do e:step({training = true}, at + 12 + i * 0.1) end
        equal(e.state, "training"); equal(e.reconnectCount, 0)
        for i = 1, 210 do e:step({training = true}, at + 13 + i) end
        equal(e.active, true); assert(e.timer:remaining(at + 223) > 6700)
    end
    equal(e.sessions, 3)
end)
test("HTC waits 20 idle minutes at 30 minutes remaining before reconnecting", function()
    local e = engine({afkMinutes = 30, afkDurationMinutes = 20})
    enterTraining(e)
    e:step({training = true, timer = 1802}, 2)
    e:step({training = true, timer = 1800}, 4)
    equal(e.state, "afk")
    e:step({reconnect = true}, 6)
    equal(e.modalFrames, 0)
    equal(e:step({reconnect = true}, 1204), nil)
    equal(e:step({reconnect = true}, 1206).kind, "reconnect")
end)
test("preview and disabled reconnect never dispatch clicks", function()
    for _, settings in ipairs({{dryRun = true}, {autoReconnect = false}}) do
        local e = engine(settings)
        for i = 0, 6 do equal(e:step({reconnect = true}, i * 2), nil) end
    end
    local e = engine({dryRun = true})
    equal(e:step({start = true}, 0), nil)
end)
test("spam sends more than 25 presses until counter completion", function()
    local input = fakeInput()
    local r = Rhythm.new(Config.new(), input)
    for i = 0, 200 do r:step({}, {visible = true, kind = "left", count = 10}, i * 0.01) end
    assert(r.spam.count > 25); equal(r.spam.kind, "left")
    for i = 201, 203 do r:step({}, {visible = true, kind = "left", count = 0}, i * 0.01) end
    equal(r.spam, nil); equal(r.done, true); equal(next(r.held), nil)
end)
test("spam survives counter flicker and locks the initial button", function()
    local input = fakeInput()
    local r = Rhythm.new(Config.new(), input)
    r:step({}, {visible = true, kind = "q", count = 25}, 0)
    for i = 1, 3 do r:step({}, nil, i * 0.02) end
    equal(r.spam.kind, "q")
    r:step({}, {visible = true, kind = "e", count = 20}, 0.08)
    equal(r.spam.kind, "q")
    for i = 1, 4 do r:step({}, nil, 0.08 + i * 0.02) end
    equal(r.spam, nil); equal(next(r.held), nil)
end)
test("completed zero never restarts spam until the counter disappears", function()
    local r = Rhythm.new(Config.new(), fakeInput())
    for i = 1, 5 do r:step({}, {visible = true, kind = "right", count = 0}, i) end
    equal(r.attempts, 0)
    for i = 6, 9 do r:step({}, nil, i) end
    r:step({}, {visible = true, kind = "right", count = 25}, 10)
    equal(r.attempts, 1)
end)
test("spam attempt cap leaves the counter monitored and releases held input", function()
    local r = Rhythm.new(Config.new({spamMaxPresses = 25}), fakeInput())
    for i = 0, 800 do r:step({}, {visible = true, kind = "e", count = 1}, i * 0.01) end
    equal(r.spam.count, 25); equal(next(r.held), nil)
end)
test("rhythm tracks motion, sends simultaneous notes once, and releases", function()
    local r = Rhythm.new(Config.new({timingOffsetMs = 0}), fakeInput())
    for i = 0, 25 do
        r:step({{id = "a", kind = "left", x = 925 + i * 5}, {id = "b", kind = "q", x = 925 + i * 5}}, nil, i * 0.01)
    end
    equal(r.attempts, 2); equal(next(r.held), nil)
    r:reset(); equal(next(r.tracks), nil)
end)
test("stationary icons and single-frame notes cannot trigger rhythm", function()
    local r = Rhythm.new(Config.new(), fakeInput())
    for i = 1, 10 do r:step({{id = "a", kind = "e", x = 1025}}, nil, i * 0.01) end
    equal(r.attempts, 0)
end)
test("partially failing input is released by reset", function()
    local input = fakeInput()
    input.down = function() error("partial delivery") end
    local r = Rhythm.new(Config.new(), input)
    equal(pcall(r.step, r, {}, {visible = true, kind = "q", count = 25}, 0), false)
    r:reset(); equal(input.events[1], "-q"); equal(next(r.held), nil)
end)

