test("pause invalidates a pending action and blocks reconnect checks", function()
    local e = engine()
    local a = e:step({start = true}, 0)
    e:setActive(false, 0.1); e:complete(a, true, 1)
    for i = 1, 5 do equal(e:step({reconnect = true}, i * 2), nil) end
    equal(e.state, "paused"); equal(e.startCount, 0)
end)
test("a single reconnect candidate pauses input but never clicks", function()
    local e = engine()
    enterTraining(e)
    equal(e:step({reconnect = true, training = true}, 4), nil)
    equal(e:canPlay({training = true}), false)
    e:step({training = true}, 6)
    equal(e.state, "training"); equal(e:canPlay({training = true}), true)
end)
test("brief gaps between prompts keep the current rhythm session", function()
    local e = engine()
    enterTraining(e)
    e:step({training = false}, 2)
    equal(e:canPlay({training = false}), true)
    e:step({training = false}, 4)
    equal(e:canPlay({training = false}), false)
end)
test("a confirmed disconnect requests an HTC rejoin at launch", function()
    local e = engine()
    equal(e:step({reconnect = true}, 0), nil)
    local a = e:step({reconnect = true}, 2)
    equal(a.kind, "rejoin")
end)
test("HTC rejoin cancels an older pending recovery action", function()
    local e = engine()
    e.state, e.since = "lost", 0; e.lastTraining = 0
    local old = e:step({menu = true, bindingsReady = true}, 10)
    equal(old.kind, "menu")
    e:step({reconnect = true}, 12)
    local a = e:step({reconnect = true}, 14)
    equal(a.kind, "rejoin")
    e:complete(old, true, 14.1); equal(e.pending, a)
end)
test("a confirmed disconnect hands retries and readiness to the teleport controller", function()
    local e = engine()
    e:step({reconnect = true}, 0)
    local a = e:step({reconnect = true}, 2)
    equal(a.kind, "rejoin"); equal(e.state, "cycling")
    e:complete(a, true, 3)
    for i = 1, 5 do
        equal(e:step({reconnect = true}, 4 + i * 10), nil)
        equal(e:step({start = true}, 5 + i * 10), nil)
    end
    equal(e:canPlay({training = true}), false)
end)
test("rejoin remains queued while a cancelled click finishes releasing", function()
    local e = engine()
    local old = e:step({start = true}, 0)
    e:step({reconnect = true}, 2)
    local rejoin = e:step({reconnect = true}, 4)
    equal(rejoin.kind, "rejoin")
    -- Main defers this action while its previous input task is unwinding.
    e.pending = nil
    e:complete(old, true, 4.1)
    rejoin = e:step({reconnect = false}, 4.2)
    equal(rejoin.kind, "rejoin")
    e:complete(rejoin, true, 4.3)
    equal(e:step({reconnect = true}, 6), nil)
    e:setActive(false, 7); equal(e.travelRequest, nil)
end)
test("HTC trains past 30 minutes and departs once at one minute remaining", function()
    local e = engine()
    enterTraining(e)
    e:step({training = true, timer = 1802, inHTC = true}, 2)
    e:step({training = true, timer = 1800, inHTC = true}, 4)
    equal(e.state, "training")
    local action = e:step({training = true, timer = 60, inHTC = true}, 1744)
    equal(action.kind, "cycle"); equal(e.state, "cycling"); equal(e:canPlay({training = true}), false)
    e:complete(action, true, 1744)
    equal(e:step({reconnect = true, timer = 59, inHTC = true}, 1746), nil)
    equal(e.state, "cycling")
end)
test("cycle needs a verified timer in HTC and respects dry run", function()
    for _, settings in ipairs({{}, {dryRun = true}}) do
        local e = engine(settings)
        equal(e:step({timer = 59, inHTC = true}, 0), nil)
        equal(e:step({timer = 58, inHTC = false}, 2), nil)
        local action = e:step({timer = 57, inHTC = true}, 4)
        if settings.dryRun then equal(action, nil) else equal(action.kind, "cycle") end
    end
end)
test("preview and disabled automatic rejoin never dispatch a teleport", function()
    for _, settings in ipairs({{dryRun = true}, {autoReconnect = false}}) do
        local e = engine(settings)
        for i = 0, 6 do equal(e:step({reconnect = true}, i * 2), nil) end
    end
    local e = engine({dryRun = true})
    equal(e:step({start = true}, 0), nil)
end)
test("spam sends more than 25 presses until counter completion", function()
    local input = fakeInput()
    local r = Rhythm.new(Config.new(), input)
    for i = 0, 200 do r:step({}, {visible = true, kind = "left", count = 10}, i * 0.01) end
    assert(r.spam.count > 25); equal(r.spam.kind, "left")
    for i = 201, 203 do r:step({}, {visible = true, kind = "left", count = 0}, i * 0.01) end
    equal(r.spam, nil); equal(r.done, true); equal(next(r.held), nil)
end)
test("spam survives counter flicker and locks the initial button", function()
    local input = fakeInput()
    local r = Rhythm.new(Config.new(), input)
    r:step({}, {visible = true, kind = "q", count = 25}, 0)
    for i = 1, 3 do r:step({}, nil, i * 0.02) end
    equal(r.spam.kind, "q")
    r:step({}, {visible = true, kind = "e", count = 20}, 0.08)
    equal(r.spam.kind, "q")
    for i = 1, 4 do r:step({}, nil, 0.08 + i * 0.02) end
    equal(r.spam, nil); equal(next(r.held), nil)
end)
test("completed zero never restarts spam until the counter disappears", function()
    local r = Rhythm.new(Config.new(), fakeInput())
    for i = 1, 5 do r:step({}, {visible = true, kind = "right", count = 0}, i) end
    equal(r.attempts, 0)
    for i = 6, 9 do r:step({}, nil, i) end
    r:step({}, {visible = true, kind = "right", count = 25}, 10)
    equal(r.attempts, 1)
end)
test("spam attempt cap leaves the counter monitored and releases held input", function()
    local r = Rhythm.new(Config.new({spamMaxPresses = 25}), fakeInput())
    for i = 0, 800 do r:step({}, {visible = true, kind = "e", count = 1}, i * 0.01) end
    equal(r.spam.count, 25); equal(next(r.held), nil)
end)
test("rhythm tracks motion, sends simultaneous notes once, and releases", function()
    local r = Rhythm.new(Config.new({timingOffsetMs = 0}), fakeInput())
    for i = 0, 25 do
        r:step({{id = "a", kind = "left", x = 925 + i * 5}, {id = "b", kind = "q", x = 925 + i * 5}}, nil, i * 0.01)
    end
    equal(r.attempts, 2); equal(next(r.held), nil)
    r:reset(); equal(next(r.tracks), nil)
end)
test("stationary icons and single-frame notes cannot trigger rhythm", function()
    local r = Rhythm.new(Config.new(), fakeInput())
    for i = 1, 10 do r:step({{id = "a", kind = "e", x = 1025}}, nil, i * 0.01) end
    equal(r.attempts, 0)
end)
test("partially failing input is released by reset", function()
    local input = fakeInput()
    input.down = function() error("partial delivery") end
    local r = Rhythm.new(Config.new(), input)
    equal(pcall(r.step, r, {}, {visible = true, kind = "q", count = 25}, 0), false)
    r:reset(); equal(input.events[1], "-q"); equal(next(r.held), nil)
end)

