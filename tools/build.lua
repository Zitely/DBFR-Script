-- Run from the repository root with Lua 5.1+ or LuaJIT. No dependencies.
local function build(modules, entry, header, outputs)
    local chunks = {header .. "\n-- Generated by tools/build.lua; edit src/*.lua.\n",
        "local __modules, __cache = {}, {}\nlocal function __require(name)\n",
        "    if __cache[name] == nil then\n        assert(__modules[name], 'Missing module: ' .. name)\n",
        "        __cache[name] = __modules[name]()\n    end\n    return __cache[name]\nend\n"}
    for _, name in ipairs(modules) do
        local file = assert(io.open("src/" .. name .. ".lua", "r"))
        local source = file:read("*a")
        file:close()
        chunks[#chunks + 1] = string.format("\n__modules[%q] = function()\nlocal require = __require\n", "src." .. name)
        chunks[#chunks + 1] = source .. "\nend\n"
    end
    chunks[#chunks + 1] = "\nreturn __require('src." .. entry .. "').start()\n"
    local bundle = table.concat(chunks)
    for _, path in ipairs(outputs) do
        local output = assert(io.open(path, "w"))
        output:write(bundle); output:close()
        print("Built " .. path)
    end
end
build({"Config", "Timer", "Engine", "Rhythm", "GuiIndex", "GameState", "GameNotes", "Bindings", "Input", "UI", "Main"}, "Main",
